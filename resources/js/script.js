class ClaimsFormManager {
    constructor() {
        this.form = document.getElementById('reclamacionForm');

        // GUARDIA: Si no estamos en la página de Contacto, paramos aquí para no dar error.
        if (!this.form) return;

        this.toggles = document.querySelectorAll('.seccion-toggle');
        this.resetBtn = this.form.querySelector('button[type="reset"]');

        // Iniciamos la lógica
        this.init();
    }

    init() {
        this.setupAccordion();
        this.expandFirstSection();
        this.setupFormHandlers();
    }

    setupAccordion() {
        this.toggles.forEach(button => {
            button.addEventListener('click', (e) => {
                // Usamos e.currentTarget para referirnos al botón, no al ícono clickeado
                const btn = e.currentTarget;
                const sectionId = btn.getAttribute('data-seccion');
                const content = document.getElementById(sectionId);
                const icon = btn.querySelector('.icono-toggle');

                if (content && icon) {
                    content.classList.toggle('hidden');
                    const isHidden = content.classList.contains('hidden');
                    // Rotamos el ícono
                    icon.style.transform = isHidden ? 'rotate(0deg)' : 'rotate(180deg)';
                }
            });
        });
    }

    expandFirstSection() {
        // Lógica para abrir siempre la primera sección al cargar
        const firstSectionId = 'seccion1';
        const firstSection = document.getElementById(firstSectionId);
        const firstIcon = document.querySelector(`[data-seccion="${firstSectionId}"] .icono-toggle`);

        if (firstSection) {
            firstSection.classList.remove('hidden');
            if (firstIcon) {
                firstIcon.style.transform = 'rotate(180deg)';
            }
        }
    }

    setupFormHandlers() {
        // 1. Manejo del ENVÍO
        this.form.addEventListener('submit', (e) => {
            e.preventDefault();

            // Aquí iría tu lógica de conexión con el backend o traducción
            alert('¡Reclamo enviado exitosamente! Recibirá una respuesta en un plazo máximo de 30 días calendario.');

            this.form.reset();

            // Esperamos un poco para cerrar las secciones visualmente
            setTimeout(() => this.resetSectionsVisibility(), 50);
        });

        // 2. Manejo del RESET (Limpiar)
        if (this.resetBtn) {
            this.resetBtn.addEventListener('click', () => {
                // Timeout para permitir que el form se limpie nativamente antes de colapsar
                setTimeout(() => {
                    this.resetSectionsVisibility();
                }, 100);
            });
        }
    }

    resetSectionsVisibility() {
        // Cerrar todas las secciones excepto la primera
        document.querySelectorAll('.seccion-contenido').forEach((content, index) => {
            const icon = document.querySelector(`[data-seccion="${content.id}"] .icono-toggle`);

            if (index === 0) {
                // La primera se queda abierta
                content.classList.remove('hidden');
                if (icon) icon.style.transform = 'rotate(180deg)';
            } else {
                // Las demás se cierran
                content.classList.add('hidden');
                if (icon) icon.style.transform = 'rotate(0deg)';
            }
        });
    }
}

class EnhancedCarousel {
    constructor() {
        this.currentSlide = 0;
        this.totalSlides = 3;
        this.autoplayInterval = null;
        this.isPlaying = true;
        this.isPaused = false;
        this.progressDuration = 5000;
        this.transitionDuration = 500;
        this.indicatorTransitionDuration = 300;
        this.carousel = document.getElementById('carousel');
        this.carouselImages = document.getElementById('carouselImages');
        this.indicators = document.querySelectorAll('.indicator');
        this.prevBtn = document.getElementById('prevBtn');
        this.nextBtn = document.getElementById('nextBtn');

        if (!this.carousel || !this.carouselImages || !this.indicators.length) {
            console.warn('Elementos del carrusel no encontrados');
            return;
        }

        this.init();
    }

    init() {
        this.prevBtn?.addEventListener('click', () => {
            this.prevSlide();
            this.restartAutoplay();
        });

        this.nextBtn?.addEventListener('click', () => {
            this.nextSlide();
            this.restartAutoplay();
        });

        this.indicators.forEach((indicator, index) => {
            indicator.addEventListener('click', () => {
                this.goToSlide(index);
                this.restartAutoplay();
            });
        });

        this.carousel.addEventListener('mouseenter', () => this.pauseAutoplay());
        this.carousel.addEventListener('mouseleave', () => this.resumeAutoplay());

        document.addEventListener('visibilitychange', () => {
            if (document.hidden) {
                this.pauseAutoplay();
            } else if (!this.isPaused) {
                this.resumeAutoplay();
            }
        });

        this.addTouchSupport();

        this.updateCarousel();
        this.updateIndicators();
        this.startAutoplay();
    }

    addTouchSupport() {
        let startX = 0;
        let endX = 0;
        const threshold = 50;

        this.carousel.addEventListener('touchstart', (e) => {
            startX = e.touches[0].clientX;
        }, { passive: true });

        this.carousel.addEventListener('touchend', (e) => {
            endX = e.changedTouches[0].clientX;
            const difference = startX - endX;

            if (Math.abs(difference) > threshold) {
                if (difference > 0) {
                    this.nextSlide();
                } else {
                    this.prevSlide();
                }
                this.restartAutoplay();
            }
        }, { passive: true });
    }

    goToSlide(slideIndex) {
        if (slideIndex === this.currentSlide) return;

        this.currentSlide = slideIndex;
        this.updateCarousel();
        this.updateIndicators();
    }

    nextSlide() {
        this.currentSlide = (this.currentSlide + 1) % this.totalSlides;
        this.updateCarousel();
        this.updateIndicators();
    }

    prevSlide() {
        this.currentSlide = (this.currentSlide - 1 + this.totalSlides) % this.totalSlides;
        this.updateCarousel();
        this.updateIndicators();
    }

    updateCarousel() {
        const translateX = -this.currentSlide * (100 / this.totalSlides);
        this.carouselImages.style.transform = `translateX(${translateX}%)`;
    }

    updateIndicators() {
        this.indicators.forEach((indicator, index) => {
            const isActive = index === this.currentSlide;
            indicator.classList.toggle('active', isActive);

            const progressBar = indicator.querySelector('.progress-bar');
            if (progressBar) {
                progressBar.style.animation = 'none';
                progressBar.offsetHeight;

                if (isActive && this.isPlaying && !this.isPaused) {
                    const fillDuration = this.progressDuration - this.indicatorTransitionDuration;
                    progressBar.style.animation = `progressFill ${fillDuration}ms linear ${this.indicatorTransitionDuration}ms forwards`;
                } else {
                    progressBar.style.transform = 'scaleX(0)';
                }
            }
        });
    }

    startAutoplay() {
        this.stopAutoplay();

        if (!this.isPlaying) return;

        this.autoplayInterval = setInterval(() => {
            if (this.isPlaying && !this.isPaused && !document.hidden) {
                this.nextSlide();
            }
        }, this.progressDuration);

        this.updateIndicators();
    }

    stopAutoplay() {
        if (this.autoplayInterval) {
            clearInterval(this.autoplayInterval);
            this.autoplayInterval = null;
        }

        this.indicators.forEach(indicator => {
            const progressBar = indicator.querySelector('.progress-bar');
            if (progressBar) {
                progressBar.style.animation = 'none';
                progressBar.style.transform = 'scaleX(0)';
            }
        });
    }

    restartAutoplay() {
        this.stopAutoplay();
        this.isPlaying = true;
        this.isPaused = false;
        this.startAutoplay();
    }

    pauseAutoplay() {
        this.isPaused = true;

        const activeIndicator = this.indicators[this.currentSlide];
        if (activeIndicator) {
            const progressBar = activeIndicator.querySelector('.progress-bar');
            if (progressBar) {
                progressBar.style.animationPlayState = 'paused';
            }
        }
    }

    resumeAutoplay() {
        if (!this.isPlaying) return;

        this.isPaused = false;

        const activeIndicator = this.indicators[this.currentSlide];
        if (activeIndicator) {
            const progressBar = activeIndicator.querySelector('.progress-bar');
            if (progressBar && progressBar.style.animation !== 'none') {
                progressBar.style.animationPlayState = 'running';
            } else {
                this.restartAutoplay();
            }
        }
    }

    destroy() {
        this.stopAutoplay();
    }
}

