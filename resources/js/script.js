function initializeAnimations() {
    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) entry.target.classList.add('animate-in');
        });
    }, { threshold: 0.1, rootMargin: '0px 0px -50px 0px' });

    document.querySelectorAll('main .flex-1, section .bg-white, .bg-gray-100, .grid > div')
        .forEach(el => observer.observe(el));
}

// Buscador con dropdown
document.querySelectorAll('.caja-busqueda').forEach(input => {
    const wrapper = input.parentElement;
    wrapper.style.position = 'relative';
    const dropdown = document.createElement('div');
    dropdown.className = 'search-dropdown';
    dropdown.style.cssText = `
        position: absolute; top: 100%; left: 0; right: 0; z-index: 9999;
        background: var(--bg-primary); border: 1px solid var(--border-color);
        border-radius: 0.5rem; margin-top: 4px; max-height: 350px;
        overflow-y: auto; box-shadow: 0 8px 24px rgba(0,0,0,0.15); display: none;
    `;
    wrapper.appendChild(dropdown);

    input.addEventListener('input', function () {
        const query = this.value.toLowerCase().trim();
        dropdown.innerHTML = '';
        if (!query) { dropdown.style.display = 'none'; return; }

        const resultados = [];
        document.querySelectorAll('.product-card').forEach(p => {
            const enlace = p.querySelector('a[href*="/producto/"]');
            const nombre = p.querySelector('a[href*="/producto/"] p, a[href*="/producto/"] + a p')?.textContent?.trim()
                        || p.querySelector('p')?.textContent?.trim();
            const precio = p.querySelector('span.fw-bold')?.textContent?.trim();
            const url = enlace?.href || null;
            if (nombre && nombre.toLowerCase().includes(query)) resultados.push({ nombre, precio, url });
        });
        document.querySelectorAll('.producto').forEach(p => {
            const enlace = p.querySelector('a[href*="/producto/"]');
            const nombre = p.querySelector('.producto-descripcion, p')?.textContent?.trim();
            const precio = p.querySelector('.precio, span.precio')?.textContent?.trim();
            const url = enlace?.href || null;
            if (nombre && nombre.toLowerCase().includes(query)) resultados.push({ nombre, precio, url });
        });

        if (!resultados.length) {
            dropdown.innerHTML = `<div style="padding:12px 16px;color:var(--text-primary);opacity:0.6;">Sin resultados para "${query}"</div>`;
        } else {
            resultados.forEach(({ nombre, precio, url }) => {
                const item = document.createElement('div');
                item.style.cssText = `padding:10px 16px;cursor:pointer;display:flex;justify-content:space-between;
                    align-items:center;color:var(--text-primary);border-bottom:1px solid var(--border-color);`;
                item.innerHTML = `<span>${nombre}</span><span style="font-weight:bold;color:var(--accent,#f59e0b);">${precio || ''}</span>`;
                item.addEventListener('mouseenter', () => item.style.background = 'var(--border-color)');
                item.addEventListener('mouseleave', () => item.style.background = '');
                item.addEventListener('click', () => {
                    dropdown.style.display = 'none';
                    if (url) {
                        window.location.href = url;
                    } else {
                        input.value = nombre;
                    }
                });
                dropdown.appendChild(item);
            });
        }
        dropdown.style.display = 'block';
    });

    document.addEventListener('click', e => {
        if (!wrapper.contains(e.target)) dropdown.style.display = 'none';
    });
});

async function procesarCompra() {
    // 1. Validar que el usuario esté autenticado
    if (!esAutenticado()) {
        alert('Debes iniciar sesión con tu cuenta para poder realizar una compra.');
        window.location.href = '/login';
        return;
    }

    const btn = document.getElementById('btn-procesar-compra');
    if (btn) {
        btn.disabled = true;
        btn.innerHTML = 'Procesando... ⏳';
    }

    try {
        // 2. Enviar la petición al backend
        const response = await fetch('/procesar-compra', {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
                'X-CSRF-TOKEN': window.APP.csrfToken // Asegúrate de que este token esté disponible en tu plantilla
            }
        });

        const data = await response.json();

        // 3. Manejar la respuesta
        if (response.ok) {
            // ¡Éxito!
            alert(`✅ ${data.mensaje}\nTu número de pedido es: ${data.codigo_pedido}`);

            // Recargamos el carrito visualmente para que aparezca vacío
            await cargarCarrito();
            await actualizarTotalCarrito();
        } else {
            // Error (ej: sin stock o carrito vacío)
            alert(`❌ No se pudo procesar: ${data.error}`);
        }
    } catch (error) {
        console.error('Error de red:', error);
        alert('Ocurrió un error de conexión al intentar procesar tu compra.');
    } finally {
        if (btn) {
            btn.disabled = false;
            btn.innerHTML = 'Confirmar Compra';
        }
    }
}
